# Generate the M5 sound tables.
#   src/sndtab.inc   (bank 3): Seq0/Seq1 note tables (ch0 / ch1, 256 bytes max each),
#                    per-id S0Start, S1Start, SRate, SCtl
#   src/sndstart.inc (bank 0): copies of the start tables for bank 0 requests
# A note byte drives one channel for one step: AUDF = byte (low 5 bits),
# AUDV = (byte >> 4) | 1; 0 ends the sequence. Tod's sounds are copied from the
# prototype ROM (bank 3 $BCE0..), sound 4 (Spario) is replaced and 10 is new.
import sys, re
# Tod's tables are read from the bank 3 source: the data after each label up to the next line
# that is not a .byte line (labels DBCE0/DBCEA/DBCF5/DBCFF are contiguous, as is DBDD2..)
src = open(sys.argv[1]).read().split('\n')
def block(label):
    k = src.index(label); out = []
    for line in src[k + 1:]:
        m = re.match(r'\s*\.byte\s+(.*)', line)
        if not m:
            if re.match(r'^D[A-Z0-9]+$', line.strip()): continue      # next data label: keep going
            break
        out += [int(v.strip().lstrip('$'), 16) for v in m.group(1).split(';')[0].split(',')]
    return out
T = block('DBCE0')                    # DBCE0 DBCEA DBCF5 DBCFF run on
RATE = T[0:10]; S1 = T[10:21]; S0 = T[21:31]; CTL = T[31:42]
SEQ = block('DBDD2')

def tod_seq(start):
    out = []
    i = start
    while SEQ[i] != 0:
        out.append(SEQ[i]); i += 1
    return out

def note(vol, freq):                 # vol 1-15 (engine forces bit0), freq 0-31
    return ((vol & 0x0E) << 4) | (freq & 0x1F) or 0x01

ids = {}                             # id -> (ch0 notes, ch1 notes, rate, ctl)
for i in range(1, 10):
    ids[i] = (tod_seq(S0[i]) if S0[i] else [], tod_seq(S1[i]) if S1[i] else [], RATE[i], CTL[i])

# 4: Spario launch - short falling "pew" (pure tone), replaces Tod's noise burst
ids[4] = ([note(12, 3), note(12, 5), note(10, 7), note(10, 9), note(8, 11), note(6, 13), note(4, 15)], [], 0, 0x84)
# 10: area start - rising four-note fanfare in two-part harmony (div-6 tone), 4 frames a step
mel = [note(12, 23), note(12, 23), note(12, 19), note(12, 19), note(12, 15), note(12, 15),
       note(14, 11), note(14, 11), note(12, 11), note(10, 11), note(8, 11), note(6, 11)]
har = [note(8, 29), note(8, 29), note(8, 24), note(8, 24), note(8, 19), note(8, 19),
       note(10, 14), note(10, 14), note(8, 14), note(6, 14), note(4, 14), note(2, 14)]
ids[10] = (mel, har, 3, 0x8C)
# the engine advances before the first note plays (as Tod's did): pad new sounds
for i in (4, 10):
    c0, c1, r, c = ids[i]
    ids[i] = ([c0[0]] + c0 if c0 else [], [c1[0]] + c1 if c1 else [], r, c)

def pack(chan):
    tab = [0]; start = {}
    for i in sorted(ids):
        s = ids[i][chan]
        if not s: start[i] = 0; continue
        start[i] = len(tab); tab += s + [0]
    assert len(tab) <= 256, (chan, len(tab))
    return tab, start

t0, st0 = pack(0); t1, st1 = pack(1)
N = 11
def row(name, vals):
    return name + '\t.byte ' + ','.join('$%02X' % v for v in vals)
def rows(name, vals):
    o = [name]
    for i in range(0, len(vals), 16): o.append('\t.byte ' + ','.join('$%02X' % v for v in vals[i:i + 16]))
    return '\n'.join(o)
s0 = [st0.get(i, 0) for i in range(N)]; s1 = [st1.get(i, 0) for i in range(N)]
rate = [ids[i][2] if i in ids else 0 for i in range(N)]; ctl = [ids[i][3] if i in ids else 0x84 for i in range(N)]
out = ['; generated by tools/sndgen.py - do not edit',
       '; sounds: 1 shot, 2 air kill, 3 ground kill, 4 Spario, 5 opener, 6 (unused), 7 extra life,',
       ';         8 ship lost, 9 game start, 10 area start (new); higher number = higher priority',
       row('S0Start', s0), row('S1Start', s1), row('SRate', rate), row('SCtl', ctl),
       rows('Seq0', t0), rows('Seq1', t1)]
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
open(sys.argv[3], 'w').write('; generated by tools/sndgen.py - bank 0 copies of the bank 3 start tables\n' +
                             row('B0S0Start', s0) + '\n' + row('B0S1Start', s1) + '\n')
print('Seq0 %d bytes, Seq1 %d bytes' % (len(t0), len(t1)))
