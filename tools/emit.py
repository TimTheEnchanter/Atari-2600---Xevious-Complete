# Emit dasm source from trace.pkl; verify by reassembly separately.
import sys,pickle
rom=open(sys.argv[1],'rb').read(); out=sys.argv[2]
code,jt,ops,SIZE=pickle.load(open('/home/claude/tools/trace.pkl','rb'))
ORG={0:0xF000,1:0xB000}
TW="VSYNC VBLANK WSYNC RSYNC NUSIZ0 NUSIZ1 COLUP0 COLUP1 COLUPF COLUBK CTRLPF REFP0 REFP1 PF0 PF1 PF2 RESP0 RESP1 RESM0 RESM1 RESBL AUDC0 AUDC1 AUDF0 AUDF1 AUDV0 AUDV1 GRP0 GRP1 ENAM0 ENAM1 ENABL HMP0 HMP1 HMM0 HMM1 HMBL VDELP0 VDELP1 VDELBL RESMP0 RESMP1 HMOVE HMCLR CXCLR".split()
TR="CXM0P CXM1P CXP0FB CXP1FB CXM0FB CXM1FB CXBLPF CXPPMM INPT0 INPT1 INPT2 INPT3 INPT4 INPT5".split()
RIOT={0x280:'SWCHA',0x281:'SWACNT',0x282:'SWCHB',0x283:'SWBCNT',0x284:'INTIM',0x285:'TIMINT',0x294:'TIM1T',0x295:'TIM8T',0x296:'TIM64T',0x297:'T1024T'}
WRITES=('STA','STX','STY')
# collect labels
lab={0:{},1:{}}
refs={0:set(),1:set()}
def sym(bank,a):
    return ('L' if (a&0xFFF) in code[bank] else 'D')+'%04X'%(ORG[bank]|(a&0xFFF))
for bk in (0,1):
    for t in jt[bk]: refs[bk].add(t)
    for o,n in code[bk].items():
        op=rom[bk*4096+o]; m,mode=ops[op]
        if n==3:
            t=rom[bk*4096+o+1]|rom[bk*4096+o+2]<<8
            if t&0xF000==ORG[bk] and (t&0xFFF)<0xFF8 and not (t&0x1FFF in (0x1FF8,0x1FF9)): refs[bk].add(t&0xFFF)
# map each ref to (labelOffset, delta): if ref lands mid-instruction, label start of instr
start_of={0:{},1:{}}
for bk in (0,1):
    for o,n in code[bk].items():
        for k in range(n): start_of[bk][o+k]=o
deflab={0:set(),1:set()}
def refexpr(bk,t):
    o=t&0xFFF
    if o in start_of[bk] and start_of[bk][o]!=o:
        s=start_of[bk][o]; deflab[bk].add(s); return sym(bk,s)+'+%d'%(o-s)
    deflab[bk].add(o); return sym(bk,o)
for bk in (0,1):
    for o in list(refs[bk]): refexpr(bk,ORG[bk]|o)
WORDS={bk:set() for bk in (0,1)}
IND={0:[0x156,0x1C0,0x1F9,0x879,0x8AC,0x8C1,0xC17,0xC1E,0xC43,0xCAB,0xCC0,0xCD1,0xCD4,0xD4A,0xD5B,0xD68,0xD69],1:[0x100,0x103,0x106,0x109,0x10C,0x157,0x188,0x28A,0x29A,0x2B0,0x2D5,0x2E2,0x2F3,0x302,0x325,0x32E,0x37B,0x3E0]}
for bk in (0,1):
    for o,n in code[bk].items():
        if o in IND[bk]: WORDS[bk].add(ORG[bk]|o)
    for o in IND[bk]: deflab[bk].add(o)
    for w in WORDS[bk]: pass
def opnd(bk,o,m,mode):
    B=lambda k: rom[bk*4096+o+k]
    if mode in('imp',): return ''
    if mode=='acc': return ''
    if mode=='imm': return '#$%02X'%B(1)
    if mode=='rel':
        r=B(1); r=r-256 if r>127 else r; return refexpr(bk,ORG[bk]|(o+2+r))
    if SIZE[mode]==2:
        z=B(1)
        if z<0x80:
            nm=TW[z&0x3F] if m in WRITES and (z&0x3F)<len(TW) else (TR[z&0xF] if m not in WRITES and (z&0xF)<len(TR) and z<0x40 else None)
            s=nm if nm and (z<0x30 if m in WRITES else z<0x10) else '$%02X'%z
        else: s='$%02X'%z
        return {'zp':s,'zpx':s+',X','zpy':s+',Y','izx':'('+s+',X)','izy':'('+s+'),Y'}[mode]
    t=B(1)|B(2)<<8
    if t&0x1000 and t&0xF000==ORG[bk] and not (t&0x1FFF in (0x1FF8,0x1FF9)): s=refexpr(bk,t)
    elif t&0x1280==0x280 and (t&0x2FF) in RIOT and t<0x1000 and t==(t&0x2FF): s=RIOT[t&0x2FF]
    else: s='$%04X'%t
    return {'abs':s,'abx':s+',X','aby':s+',Y','ind':'('+s+')'}[mode]
FREE={(0,0xFE5):19,(1,0xFB4):68,(1,0x95B):165,(1,0x5D6):42,(1,0x4D6):44,(1,0x7D8):42,(1,0x1EB):21,(1,0x2F8):8,(1,0x3EF):19}
FREEEND={(bk,o+n):(bk,o) for (bk,o),n in FREE.items()}
L=[]
L.append('; Xevious (Atari 2600) - prototype 1984-01-18, Tod Frye / Atari. 8K F8 bankswitching.')
L.append('; Disassembly regenerated by tracing + runtime coverage. Reassembles byte-identical with dasm -f3.')
L.append('\tprocessor 6502')
for i,n in enumerate(TW): L.append('%-8s= $%02X'%(n,i))
for i,n in enumerate(TR): L.append('%-8s= $%02X'%(n,i))
for a,n in sorted(RIOT.items()): L.append('%-8s= $%04X'%(n,a))
for bk in (0,1):
    L.append(''); L.append(';'+'='*70); L.append('; BANK %d  (runs at $%04X)'%(bk,ORG[bk])); L.append(';'+'='*70)
    L.append('\tSEG bank%d'%bk); L.append('\tORG $%04X'%(bk*0x1000)); L.append('\tRORG $%04X'%ORG[bk])
    o=0; data=[]
    def flush():
        global data
        for i in range(0,len(data),8):
            L.append('\t.byte '+','.join('$%02X'%x for x in data[i:i+8]))
        data=[]
    while o<4096:
        if o in deflab[bk] or o in (0xFF8,0xFFA) or (bk,o) in FREE or (bk,o) in FREEEND:
            flush()
            if (bk,o) in FREEEND: L.append('; end free %04X'%(ORG[bk]+FREEEND[(bk,o)][1]))
            if (bk,o) in FREE: L.append('FREE_%04X\t; ---- unused space (%d bytes) ----'%(ORG[bk]+o,FREE[(bk,o)]))
            if o==0xFF8: L.append('; bankswitch hotspots / vectors')
            if o in deflab[bk]: L.append(sym(bk,o))
        if o in code[bk]:
            flush(); n=code[bk][o]; op=rom[bk*4096+o]; m,mode=ops[op]
            s=opnd(bk,o,m,mode)
            mn=m
            if SIZE[mode]==3 and mode!='ind' and (rom[bk*4096+o+2]==0): mn=m+'.w'
            L.append('\t%-6s %-22s; %04X'%(mn,s,ORG[bk]+o) if s else '\t%-6s %-22s; %04X'%(mn,'',ORG[bk]+o))
            o+=n
        elif o+1<4096 and o+1 not in code[bk] and o+1 not in deflab[bk] and (rom[bk*4096+o]|rom[bk*4096+o+1]<<8) in WORDS[bk]:
            flush(); w=rom[bk*4096+o]|rom[bk*4096+o+1]<<8
            L.append('\t.word %-21s; %04X'%(sym(bk,w),ORG[bk]+o)); o+=2
        else:
            data.append(rom[bk*4096+o]); o+=1
            if o<4096 and (o in deflab[bk] or o in code[bk] or o in (0xFF8,0xFFA) or (bk,o) in FREE or (bk,o) in FREEEND): flush()
    flush()
open(out,'w').write('\n'.join(L)+'\n')
print('lines',len(L))
